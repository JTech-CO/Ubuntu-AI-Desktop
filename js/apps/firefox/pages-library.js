/**
 * @param {string} url
 * @returns {boolean} true for a page implemented in this module
 */
export function isLocalUrl(url) {
  const key = String(url || '').trim().toLowerCase();
  return Object.prototype.hasOwnProperty.call(LOCAL_TITLES, key);
}

/**
 * Tab title for a local page.
 * @param {string} url
 * @returns {string}
 */
export function titleForLocal(url) {
  const key = String(url || '').trim().toLowerCase();
  return LOCAL_TITLES[key] || key;
}

/**
 * Render one of the local pages.
 * @param {string} url
 * @param {object} browser
 * @returns {HTMLElement|null} null when `url` is not a local page
 */
export function renderLocalPage(url, browser) {
  switch (String(url || '').trim().toLowerCase()) {
    case HOME_URL:
    case NEWTAB_URL:
      return renderStartPage(browser);
    case BLANK_URL:
      return renderBlankPage();
    case PREFS_URL:
      return renderPreferencesPage(browser);
    case HISTORY_URL:
      return renderHistoryPage(browser);
    case BOOKMARKS_URL:
      return renderBookmarksPage(browser);
    case ABOUT_URL:
      return renderAboutIndexPage(browser);
    default:
      return null;
  }
}
