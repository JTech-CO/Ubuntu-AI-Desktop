/**
 * js/apps/firefox/pages-library.js — the browser's own library pages, split out
 * of `pages.js` to keep both files a readable size.
 *
 *   about:about         index of the pages below
 *   about:preferences   Firefox Settings, including the Live web / AI switch
 *   about:history       history library (Ctrl+H)
 *   about:bookmarks     bookmark library
 *
 * Same rules as `pages.js`: everything is rendered locally, and every value
 * that originates outside this file — URLs, page titles, typed queries — is
 * inserted through `h({ text })`, i.e. `textContent`. `innerHTML` is never used.
 *
 * The dependency runs one way, `pages-library.js` -> `pages.js`, so there is no
 * import cycle: `pages.js` knows nothing about this module.
 */

import { h } from '../../core/dom.js';
import {
  HOME_URL,
  NEWTAB_URL,
  BLANK_URL,
  PREFS_URL,
  HISTORY_URL,
  BOOKMARKS_URL,
  ABOUT_URL,
  MODE_LIVE,
  MODE_AI,
  fxIcon,
  faviconChip,
  button,
  prettyUrl,
  clockText,
  dayLabel,
  renderStartPage,
  renderBlankPage,
} from './pages.js';

/** Title shown in the tab strip for each local page. */
const LOCAL_TITLES = {
  [HOME_URL]: 'Ubuntu Start',
  [NEWTAB_URL]: 'New Tab',
  [BLANK_URL]: 'about:blank',
  [PREFS_URL]: 'Settings',
  [HISTORY_URL]: 'History',
  [BOOKMARKS_URL]: 'Bookmarks',
  [ABOUT_URL]: 'About About',
};

/* ------------------------------------------------------ shared pieces --- */

/**
 * Section wrapper used by the pages in this module.
 * @param {string} title
 * @param {...any} children
 * @returns {HTMLElement}
 */
function panel(title, ...children) {
  return h('section.fx-panel', {}, h('h2.fx-panel-title', { text: title }), ...children);
}

/**
 * Empty-state block.
 * @param {string} iconName
 * @param {string} title
 * @param {string} body
 * @returns {HTMLElement}
 */
function emptyState(iconName, title, body) {
  return h(
    'div.fx-empty',
    {},
    fxIcon(iconName, 30, { class: 'fx-empty-icon' }),
    h('p.fx-empty-title', { text: title }),
    h('p.fx-empty-body', { text: body })
  );
}

