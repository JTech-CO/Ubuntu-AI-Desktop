/**
 * about:about — index of the pages this browser implements locally.
 * @param {object} browser
 * @returns {HTMLElement}
 */
export function renderAboutIndexPage(browser) {
  const rows = [
    { url: HOME_URL, note: 'Ubuntu Start page' },
    { url: NEWTAB_URL, note: 'New tab page' },
    { url: BLANK_URL, note: 'Empty document' },
    { url: PREFS_URL, note: 'Browser settings' },
    { url: HISTORY_URL, note: 'Browsing history' },
    { url: BOOKMARKS_URL, note: 'Saved bookmarks' },
    { url: ABOUT_URL, note: 'This page' },
  ];
  const list = h('ul.fx-about-list');
  for (const row of rows) {
    list.appendChild(
      h(
        'li.fx-about-item',
        {},
        h('button.fx-link', { type: 'button', text: row.url, on: { click: () => browser.navigate(row.url) } }),
        h('span.fx-about-note', { text: row.note })
      )
    );
  }
  return h(
    'div.fx-page.fx-about-page',
    {},
    h('h1.fx-page-title', { text: 'List of about: pages' }),
    h('p.fx-page-lede', { text: 'These pages are part of the browser itself. They are rendered locally and never generated by AI.' }),
    list
  );
}

/* ---------------------------------------------------- about:preferences -- */

function prefRow(label, description, control) {
  return h(
    'div.fx-pref-row',
    {},
    h(
      'div.fx-pref-labels',
      {},
      h('div.fx-pref-label', { text: label }),
      description ? h('div.fx-pref-desc', { text: description }) : null
    ),
    h('div.fx-pref-control', {}, control)
  );
}

function checkbox(checked, onChange, label) {
  const input = h('input.fx-checkbox', { type: 'checkbox', checked: !!checked });
  input.addEventListener('change', () => onChange(input.checked));
  return h('label.fx-checkbox-wrap', {}, input, h('span', { text: label }));
}

function selectField(options, value, onChange) {
  const sel = h('select.fx-select');
  for (const opt of options) sel.appendChild(h('option', { value: opt.value, text: opt.label }));
  sel.value = value;
  sel.addEventListener('change', () => onChange(sel.value));
  return sel;
}

/**
 * about:preferences — a working Firefox Settings page. Every control writes
 * through `browser.setPref` and takes effect immediately.
 * @param {object} browser
 * @returns {HTMLElement}
 */
export function renderPreferencesPage(browser) {
  const page = h('div.fx-page.fx-prefs');
  const body = h('div.fx-prefs-body');

  const build = () => {
    const prefs = browser.prefs();
    const live = browser.mode() === MODE_LIVE;
    while (body.firstChild) body.removeChild(body.firstChild);

    /* --- Browsing mode ------------------------------------------------- */
    body.appendChild(
      panel(
        'Browsing mode',
        prefRow(
          'How pages are loaded',
          live
            ? 'Live web really fetches the address in a sandboxed frame. Sites that refuse to be framed get an interstitial, never a fake page.'
            : 'AI simulation asks Gemini to write the content of the address you typed. Nothing is fetched from the site.',
          selectField(
            [
              { value: MODE_LIVE, label: 'Live web (real network)' },
              { value: MODE_AI, label: 'AI simulation (Gemini)' },
            ],
            live ? MODE_LIVE : MODE_AI,
            (value) => {
              browser.setMode(value);
              build();
            }
          )
        )
      )
    );

    /* --- General ------------------------------------------------------- */
    const homeOptions = [
      { value: HOME_URL, label: 'Ubuntu Start (default)' },
      { value: BLANK_URL, label: 'Blank Page' },
      { value: 'custom', label: 'Custom URL…' },
    ];
    const isCustom = prefs.homepage !== HOME_URL && prefs.homepage !== BLANK_URL;
    const customInput = h('input.fx-input', {
      type: 'text',
      value: isCustom ? prefs.homepage : prefs.customHome || '',
      placeholder: 'https://ubuntu.com/',
      'aria-label': 'Custom home page address',
    });
    customInput.addEventListener('change', () => {
      const value = customInput.value.trim();
      browser.setPref('customHome', value);
      if (value !== '') browser.setPref('homepage', value);
    });
    const customRow = prefRow('Custom home page', 'Used when “Custom URL…” is selected above.', customInput);
    customRow.hidden = !isCustom;

    body.appendChild(
      panel(
        'Home',
        prefRow(
          'Homepage and new windows',
          'Shown when you press the Home button or open a new window.',
          selectField(homeOptions, isCustom ? 'custom' : prefs.homepage, (value) => {
            if (value === 'custom') {
              const custom = (prefs.customHome || '').trim();
              browser.setPref('homepage', custom !== '' ? custom : HOME_URL);
            } else {
              browser.setPref('homepage', value);
            }
            build();
          })
        ),
        customRow,
        prefRow(
          'Startup',
          null,
          checkbox(prefs.restoreSession, (v) => browser.setPref('restoreSession', v), 'Open previous windows and tabs')
        ),
        prefRow(
          'Tabs',
          null,
          checkbox(prefs.warnOnQuit, (v) => browser.setPref('warnOnQuit', v), 'Confirm before closing multiple tabs')
        )
      )
    );

    /* --- Search -------------------------------------------------------- */
    body.appendChild(
      panel(
        'Search',
        prefRow(
          'Default search engine',
          live
            ? 'Real results from the DuckDuckGo Instant Answer API and the Wikipedia search API — the two engines that allow cross-origin requests without a key.'
            : 'Queries are answered by Google Gemini using your own API key.',
          h('div.fx-pref-static', { text: live ? 'DuckDuckGo + Wikipedia' : 'Gemini (simulated)' })
        ),
        prefRow(
          'Address bar',
          null,
          checkbox(prefs.acSuggest, (v) => browser.setPref('acSuggest', v), 'Suggest browsing history and bookmarks')
        ),
        prefRow(
          'API key',
          'Stored only in this browser profile. Nothing is sent anywhere else.',
          button('Open AI Configuration', () => browser.openAiSettings(), { icon: 'key' })
        )
      )
    );

    /* --- Reader -------------------------------------------------------- */
    const sizeInput = h('input.fx-range', {
      type: 'range',
      min: '14',
      max: '26',
      step: '1',
      value: String(prefs.readerFontSize),
      'aria-label': 'Reader font size',
    });
    const sizeValue = h('span.fx-range-value', { text: `${prefs.readerFontSize} px` });
    sizeInput.addEventListener('input', () => {
      const value = Number(sizeInput.value);
      sizeValue.textContent = `${value} px`;
      browser.setPref('readerFontSize', value);
    });

    body.appendChild(
      panel(
        'Reader View',
        prefRow('Font size', 'Applies to pages opened in Reader View.', h('div.fx-range-wrap', {}, sizeInput, sizeValue)),
        prefRow(
          'Colour scheme',
          null,
          selectField(
            [
              { value: 'light', label: 'Light' },
              { value: 'sepia', label: 'Sepia' },
            ],
            prefs.readerTheme,
            (v) => browser.setPref('readerTheme', v)
          )
        )
      )
    );

    /* --- Privacy ------------------------------------------------------- */
    const historyCount = browser.history().length;
    const bookmarkCount = browser.bookmarks().length;
    body.appendChild(
      panel(
        'Privacy & Security',
        prefRow(
          'Browsing history',
          `${historyCount} ${historyCount === 1 ? 'entry' : 'entries'} stored in this profile.`,
          button('Clear History…', () => {
            browser.clearHistory().then((done) => {
              if (done) build();
            });
          }, { icon: 'trash', variant: 'danger' })
        ),
        prefRow(
          'Bookmarks',
          `${bookmarkCount} ${bookmarkCount === 1 ? 'bookmark' : 'bookmarks'} stored in this profile.`,
          button('Remove All Bookmarks…', () => {
            browser.clearBookmarks().then((done) => {
              if (done) build();
            });
          }, { icon: 'trash', variant: 'danger' })
        ),
        prefRow(
          'Network',
          null,
          h('div.fx-pref-static', {
            text: live
              ? 'In Live web mode the pages you open are fetched by the real browser, so the sites you visit see this machine exactly as any other visit. Frames are sandboxed and are never scripted by this app.'
              : 'In AI simulation mode this browser never contacts a website. The only outbound request is to the Gemini API when you search or open a page.',
          })
        )
      )
    );
  };

  build();
  page.appendChild(h('h1.fx-page-title', { text: 'Settings' }));
  page.appendChild(body);
  return page;
}

